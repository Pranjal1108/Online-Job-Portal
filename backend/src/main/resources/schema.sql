CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(80) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL, role VARCHAR(20) NOT NULL CHECK(role IN ('candidate','recruiter')),
 headline VARCHAR(160) NOT NULL DEFAULT '', location VARCHAR(100) NOT NULL DEFAULT '',
 skills VARCHAR(500) NOT NULL DEFAULT '', bio VARCHAR(2000) NOT NULL DEFAULT '',
 website VARCHAR(300) NOT NULL DEFAULT '', created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recruiter_id BIGINT REFERENCES users(id),
 title VARCHAR(120) NOT NULL, company VARCHAR(120) NOT NULL, location VARCHAR(100) NOT NULL,
 category VARCHAR(40) NOT NULL, job_type VARCHAR(30) NOT NULL, workplace VARCHAR(20) NOT NULL,
 salary_min INT NOT NULL, salary_max INT NOT NULL, description VARCHAR(8000) NOT NULL,
 skills VARCHAR(500) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE,
 is_demo BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(salary_min >= 0 AND salary_max >= salary_min)
);
CREATE TABLE IF NOT EXISTS saved_jobs (
 user_id BIGINT NOT NULL REFERENCES users(id), job_id BIGINT NOT NULL REFERENCES jobs(id),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id, job_id)
);
CREATE TABLE IF NOT EXISTS applications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id),
 job_id BIGINT NOT NULL REFERENCES jobs(id), cover_letter VARCHAR(4000) NOT NULL,
 resume_url VARCHAR(500) NOT NULL DEFAULT '', status VARCHAR(30) NOT NULL DEFAULT 'Submitted',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, UNIQUE(user_id, job_id),
 CHECK(status IN ('Submitted','Reviewing','Shortlisted','Rejected','Withdrawn'))
);
CREATE INDEX IF NOT EXISTS idx_jobs_recruiter ON jobs(recruiter_id);
CREATE INDEX IF NOT EXISTS idx_applications_user ON applications(user_id);
CREATE INDEX IF NOT EXISTS idx_applications_job ON applications(job_id);
